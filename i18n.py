def translate(language: str, key: str, **values: Any) -> str:
    selected = language if language in TRANSLATIONS else "en"
    template = TRANSLATIONS[selected].get(key) or TRANSLATIONS["en"].get(key) or key
    try:
        return template.format(**values)
    except (KeyError, ValueError):
        return template


def localize_known_error(language: str, message: str) -> str:
    normalized = message.replace("ERROR: ", "").strip()
    if "yt-dlp command was not found" in normalized:
        return translate(language, "analysis.engine_missing")
    if normalized.startswith("No downloadable media"):
        return translate(language, "analysis.no_media")
    if "Spotify" in normalized:
        return translate(language, "analysis.spotify_failed")
    return normalized
